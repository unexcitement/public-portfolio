#!/usr/bin/env python3
"""
Generates GLOSSARY.md and docs/roles/*.md from docs/glossary.toml.

Standard library only (Python 3.11+). Usage:
    python3 scripts/build_glossary.py          # write files
    python3 scripts/build_glossary.py --check  # exit 1 if files are stale
"""

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "docs" / "glossary.toml"
GLOSSARY = ROOT / "GLOSSARY.md"
ROLES_DIR = ROOT / "docs" / "roles"
HEADER = "<!-- Generated by scripts/build_glossary.py from docs/glossary.toml. Edit the TOML, not this file. -->\n"


def project_link(num, projects, prefix):
    p = projects[num]
    return f"[{num} {p['name']}]({prefix}projects/{p['dir']}/profile.md)"


def validate(data):
    projects = data["projects"]
    slugs = {r["slug"] for r in data["roles"]}
    errors = []
    for t in data["terms"]:
        errors += [f"{t['term']}: unknown project {n}" for n in t["projects"] if n not in projects]
        errors += [f"{t['term']}: unknown role {r}" for r in t["roles"] if r not in slugs]
    for r in data["roles"]:
        errors += [f"role {r['slug']}: unknown project {n}" for n, _ in r["flagship"] if n not in projects]
    if errors:
        sys.exit("glossary.toml errors:\n  " + "\n  ".join(errors))


def render_terms(terms, projects, roles_by_slug, prefix, role_prefix, show_roles):
    lines = []
    letter = None
    for t in terms:
        first = t["term"][0].upper()
        if first != letter:
            letter = first
            lines += [f"### {letter}", ""]
        links = ", ".join(project_link(n, projects, prefix) for n in t["projects"])
        lines.append(f"**{t['term']}**  ")
        lines.append(f"{t['definition']}  ")
        lines.append(f"*Projects:* {links}  ")
        if show_roles:
            roles = ", ".join(
                f"[{roles_by_slug[s]['title']}]({role_prefix}{s}.md)" for s in t["roles"]
            )
            lines.append(f"*Roles:* {roles}")
        lines.append("")
    return lines


def build_glossary(data):
    projects = data["projects"]
    roles_by_slug = {r["slug"]: r for r in data["roles"]}
    terms = sorted(data["terms"], key=lambda t: t["term"].lower())
    letters = sorted({t["term"][0].upper() for t in terms})

    lines = [
        HEADER,
        "# Glossary",
        "",
        "Plain-language definitions of the patterns and technologies that appear across this portfolio, each linked to the projects that use them.",
        "",
        "Looking for a specific kind of experience? The same terms are grouped by job role:",
        "",
    ]
    for r in data["roles"]:
        lines.append(f"- [{r['title']}](docs/roles/{r['slug']}.md): {r['summary']}")
    lines += ["", "**Jump to:** " + " · ".join(f"[{l}](#{l.lower()})" for l in letters), ""]
    lines += render_terms(terms, projects, roles_by_slug, "", "docs/roles/", show_roles=True)
    return "\n".join(lines).rstrip() + "\n"


def build_role(role, data):
    projects = data["projects"]
    roles_by_slug = {r["slug"]: r for r in data["roles"]}
    terms = sorted(
        (t for t in data["terms"] if role["slug"] in t["roles"]), key=lambda t: t["term"].lower()
    )
    flagship_nums = [n for n, _ in role["flagship"]]
    related = sorted({n for t in terms for n in t["projects"]} - set(flagship_nums))

    lines = [
        HEADER,
        f"# {role['title']}",
        "",
        f"**For:** {role['audience']}",
        "",
        role["summary"],
        "",
        "## Start with these projects",
        "",
        "| Project | Why it matters for this role |",
        "|---|---|",
    ]
    for num, why in role["flagship"]:
        lines.append(f"| {project_link(num, projects, '../../')} | {why} |")
    if related:
        lines += [
            "",
            "**Also relevant:** " + ", ".join(project_link(n, projects, "../../") for n in related),
        ]
    lines += ["", "## Role glossary", ""]
    lines += render_terms(terms, projects, roles_by_slug, "../../", "", show_roles=False)
    lines += [
        "---",
        "",
        "[All roles](README.md) · [Full glossary](../../GLOSSARY.md) · [Portfolio home](../../README.md)",
    ]
    return "\n".join(lines).rstrip() + "\n"


def build_roles_index(data):
    lines = [
        HEADER,
        "# Portfolio by Role",
        "",
        "Each page below picks the projects most relevant to one kind of role and defines the terms that matter for it.",
        "",
        "| Role | Who it is for | Focus |",
        "|---|---|---|",
    ]
    for r in data["roles"]:
        lines.append(f"| [{r['title']}]({r['slug']}.md) | {r['audience']} | {r['summary']} |")
    lines += ["", "[Full glossary](../../GLOSSARY.md) · [Portfolio home](../../README.md)"]
    return "\n".join(lines).rstrip() + "\n"


def main():
    check = "--check" in sys.argv
    data = tomllib.loads(DATA.read_text())
    validate(data)

    outputs = {GLOSSARY: build_glossary(data), ROLES_DIR / "README.md": build_roles_index(data)}
    for r in data["roles"]:
        outputs[ROLES_DIR / f"{r['slug']}.md"] = build_role(r, data)

    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        sys.exit(1 if stale else 0)

    ROLES_DIR.mkdir(parents=True, exist_ok=True)
    for p, text in outputs.items():
        p.write_text(text)
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
